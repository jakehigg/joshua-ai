"""Offline tests for the parse of an assignment's report and plan."""

from __future__ import annotations

from pathlib import Path

import pytest
from joshua_gateway import viewer_report as rp

REPORTS = Path(__file__).parent / "fixtures" / "reports"


def fixture(name: str) -> str:
    return (REPORTS / f"{name}.md").read_text()


def test_a_full_report_has_each_section() -> None:
    report = rp.parse(fixture("full"))
    assert report.structured and not report.generated
    assert report.title == "Clean up the docs"
    assert report.lede.startswith("Your wiki has no dead links now")
    assert report.preamble == ""
    assert list(report.sections) == [
        rp.HIGHLIGHTS,
        rp.ASKED,
        rp.DONE,
        rp.OUTPUTS,
        rp.DECISIONS,
        rp.FOLLOW_UPS,
        rp.COST,
    ]
    assert report.extra == []
    highlights = report.sections[rp.HIGHLIGHTS].items
    assert [h.lead for h in highlights] == [
        "42 dead links fixed",
        "12 tasks filed",
        "3 pages renamed",
        "0 pages deleted",
    ]
    assert highlights[0].body == "across 18 pages, in one merge request."
    assert highlights[3].body == "every old page still has a redirect."


def test_a_report_with_no_highlights_keeps_the_rest() -> None:
    report = rp.parse(fixture("no_highlights"))
    assert report.structured
    assert report.get(rp.HIGHLIGHTS) is None
    assert [section.title for section in report.extra] == ["Notes"]
    decisions = report.get(rp.DECISIONS)
    assert decisions is not None and decisions.empty and decisions.items == []


def test_a_report_with_none_of_the_headings_is_not_structured() -> None:
    report = rp.parse(fixture("plain"))
    assert not report.structured
    assert report.sections == {}
    # A Cost section alone does not make a report structured.
    assert not rp.parse("# T\n\nText.\n\n## Cost\n\n- Turns: 3").structured
    assert not rp.parse(None).structured


def test_a_generated_report_is_marked() -> None:
    report = rp.parse(fixture("generated"))
    assert report.structured and report.generated
    assert report.lede.startswith("Generated by the runner at failed, 2026-11-09 14:48 UTC.")
    # The headings of the plan inside What was done are unknown sections.
    assert [section.title for section in report.extra] == ["Steps", "Decisions"]
    (decision,) = report.sections[rp.DECISIONS].items
    assert rp.decision_question(decision) == (
        "Which project gets the issues?",
        "The assignment waits for your answer.",
    )
    assert rp.turns(report.sections[rp.COST].body) == 9


def test_a_heading_in_a_code_block_is_not_a_heading() -> None:
    text = "# T\n\nLede.\n\n## What was done\n\n```\n## Outputs\n```\n\nEnd.\n"
    report = rp.parse(text)
    assert report.get(rp.OUTPUTS) is None
    assert "## Outputs" in report.sections[rp.DONE].body


def test_the_text_after_the_lede_is_the_preamble() -> None:
    report = rp.parse("# T\n\nThe lede\non two lines.\n\nMore text.\n\n## What was done\n\nx")
    assert report.lede == "The lede on two lines."
    assert report.preamble == "More text."


def test_a_heading_is_matched_loosely_and_only_once() -> None:
    report = rp.parse("## FOLLOW UPS:\n- a\n## What was done\nx\n## What was done\ny")
    assert report.sections[rp.FOLLOW_UPS].items == [rp.Item(text="a")]
    assert report.sections[rp.DONE].body == "x"
    assert [(s.title, s.body) for s in report.extra] == [("What was done", "y")]
    assert report.title == "" and report.lede == ""


def test_list_items_keep_their_lines_and_leave_the_rest() -> None:
    body = (
        "Intro.\n\n"
        "1. **First?** Some context\n"
        "   on two lines.\n\n"
        "   - a nested point\n"
        "2) __Second__: more\n"
        "lazy line\n\n"
        "Outro.\n\n"
        "```\n- not an item\n```"
    )
    items, rest = rp.list_items(body)
    assert [item.lead for item in items] == ["First?", "Second"]
    assert items[0].body == "Some context\non two lines.\n\n- a nested point"
    assert items[1].body == "more\nlazy line"
    assert rest == "Intro.\n\n\nOutro.\n\n```\n- not an item\n```"


def test_an_item_with_no_lead() -> None:
    (item,) = rp.list_items("- just text\n  more")[0]
    assert item == rp.Item(text="just text\nmore")
    assert rp.decision_question(item) == ("just text", "more")


