"""Read the report and the plan of an assignment by their Markdown structure.

The report is one Markdown text with fixed headings, so Joshua reads it as
it is:

```
# <title>
<one sentence: what the person now has>
## Highlights
## What was asked
## What was done
## Outputs
## Decisions for you
## Follow-ups
## Cost
```

The viewer gives each section its own element, and this module finds the
parts. The parse is tolerant: a missing section is None, an unknown heading
goes into :attr:`Report.extra`, and a text with none of the known headings
gives a :class:`Report` with ``structured`` False, which the viewer shows as
plain Markdown. A heading inside a fenced code block is not a heading.

The plan is Markdown with task boxes (``- [x] done``, ``- [ ] to do``).
:func:`plan_progress` counts them and finds the next step.

Each section, list item, and the preamble also knows its line in the text
(from 1), so the viewer can anchor a comment to the line of a card.

The functions here return text and numbers, never HTML.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

# The known sections, by their normal name (see :func:`_key`).
HIGHLIGHTS = "highlights"
ASKED = "what was asked"
DONE = "what was done"
OUTPUTS = "outputs"
DECISIONS = "decisions for you"
FOLLOW_UPS = "follow-ups"
COST = "cost"
_KNOWN = frozenset({HIGHLIGHTS, ASKED, DONE, OUTPUTS, DECISIONS, FOLLOW_UPS, COST})
# A plan often has a "## Decisions" heading, and a stop report holds the plan,
# so "Decisions" alone is not the decisions section.
_ALIASES = {"follow ups": FOLLOW_UPS, "followups": FOLLOW_UPS}

# The second line of a report that the runner wrote, not the worker.
GENERATED = "Generated by the runner at"

_FENCE = re.compile(r"^\s{0,3}(```|~~~)")
_H1 = re.compile(r"^#\s+(.*?)\s*#*\s*$")
_H2 = re.compile(r"^##\s+(.*?)\s*#*\s*$")
_ITEM = re.compile(r"^( {0,1})(?:[-*+]|\d{1,3}[.)])\s+(.*)$")
_LEAD = re.compile(r"^(?:\*\*(.+?)\*\*|__(.+?)__)[\s:.,;—–-]*(.*)$", re.DOTALL)
_BOX = re.compile(r"^\s*(?:[-*+]|\d{1,3}[.)])\s+\[([ xX])\]\s+(.*)$")
_NEXT = re.compile(r"\*\*\s*next\s*:?\s*\*\*\s*:?\s*", re.IGNORECASE)
_NONE = re.compile(
    r"^(?:none(?: recorded| yet)?|nothing|n/?a|no\b[^\n]{0,60}|-+)\.?$", re.IGNORECASE
)
_LINK = re.compile(r"\[(?P<title>[^\]]*)\]\((?P<ref><[^>]*>|[^)\s]+)[^)]*\)")
_CODE = re.compile(r"`(?P<ref>[^`]+)`")
_KIND = re.compile(r"^(?P<kind>[A-Za-z][\w /-]{0,39}?)\s*:\s+(?P<rest>.*)$", re.DOTALL)
_DASH = re.compile(r"\s+[—–-]{1,2}\s+")
_LEAD_DASH = re.compile(r"^\s*[—–:-]{1,2}\s*")
_TRAIL_DASH = re.compile(r"\s*[—–:-]{1,2}\s*$")
_TURNS = (
    re.compile(r"\bturns?\b\s*[:=]?\s*(\d[\d,  ]*)", re.IGNORECASE),
    re.compile(r"(\d[\d,  ]*)\s+turns?\b", re.IGNORECASE),
)


@dataclass(frozen=True)
class Item:
    """One list item of a section: the bold lead, when any, and the rest.

    ``text`` is the whole item as Markdown; ``lead`` is the bold text at its
    start, with no ``**``; ``body`` is the Markdown after the lead. ``line``
    is the line of the item in the text it came from, from 0.
    """

    text: str
    lead: str = ""
    body: str = ""
    line: int = field(default=0, compare=False)


@dataclass(frozen=True)
class Section:
    """A ``##`` section: its heading as written and its Markdown body.

    ``line`` is the line of the heading in the report, ``start`` the line of
    the first line of ``body``, and ``end`` the last line of the section, each
    from 1. A section that :func:`parse` did not make has 0 for each."""

    title: str
    body: str
    line: int = field(default=0, compare=False)
    start: int = field(default=0, compare=False)
    end: int = field(default=0, compare=False)

    @property
    def items(self) -> list[Item]:
        """The top-level list items of the body."""
        return list_items(self.body)[0]

    @property
    def rest(self) -> str:
        """The body with the top-level list items taken out."""
        return list_items(self.body)[1]

    @property
    def empty(self) -> bool:
        """True when the body says nothing: blank, or "None." and the like."""
        return is_none(self.body)


@dataclass
class Report:
    """A report, cut at its headings."""

    structured: bool
    title: str = ""
    lede: str = ""
    preamble: str = ""
    sections: dict[str, Section] = field(default_factory=dict)
    extra: list[Section] = field(default_factory=list)
    generated: bool = False
    # The lines (from 1) of the preamble and of the first ``##`` heading.
    preamble_line: int = 0
    first_section: int = 0

    def get(self, key: str) -> Section | None:
        """A known section, or None when the report has no such heading."""
        return self.sections.get(key)


@dataclass(frozen=True)
class OutputLine:
    """One line of the Outputs section, as far as it can be read."""

    kind: str
    ref: str
    title: str
    note: str
    line: int = field(default=0, compare=False)


@dataclass(frozen=True)
class PlanProgress:
    """The task boxes of a plan: how many are ticked, and the next step."""

    done: int
    total: int
    next_step: str

    @property
    def percent(self) -> float:
        return 100.0 * self.done / self.total if self.total else 0.0


def normal(title: str) -> str:
    """A heading as a key: lower case, single spaces, no colon at the end."""
    key = " ".join(title.strip().rstrip(":").lower().split())
    return _ALIASES.get(key, key)


def _lines_outside_fences(lines: list[str]) -> list[bool]:
    """For each line, True when it is outside a fenced code block."""
    marks: list[bool] = []
    fence: str | None = None
    for line in lines:
        match = _FENCE.match(line)
        if fence is None:
            marks.append(True)
            if match:
                fence = match.group(1)
        else:
            marks.append(False)
            if match and match.group(1) == fence:
                fence = None
    return marks


def is_none(text: str | None) -> bool:
    """True for a body that says nothing: blank, "None.", "No decisions.", "-"."""
    stripped = (text or "").strip()
    return not stripped or bool(_NONE.match(stripped))


def parse(text: str | None) -> Report:
    """Cut ``text`` at its ``#`` and ``##`` headings."""
    lines = (text or "").replace("\r\n", "\n").split("\n")
    outside = _lines_outside_fences(lines)
    title = ""
    head: list[str] = []
    chunks: list[tuple[str, int, list[str]]] = []
    for number, (line, free) in enumerate(zip(lines, outside, strict=True), start=1):
        h2 = _H2.match(line) if free else None
        if h2:
            chunks.append((h2.group(1), number, []))
            continue
        h1 = _H1.match(line) if free and not chunks and not title else None
        if h1 and not "".join(head).strip():
            title = h1.group(1)
            continue
        (chunks[-1][2] if chunks else head).append(line)

    known = [name for name, _, _ in chunks if normal(name) in _KNOWN - {COST}]
    if not known:
        return Report(structured=False, title=title)

    preamble = "\n".join(head).strip()
    lede, _, after = preamble.partition("\n\n")
    whole = "\n".join(lines)
    first_section = chunks[0][1]
    report = Report(
        structured=True,
        title=title,
        lede=" ".join(lede.split()),
        preamble=after.strip(),
        generated=lede.strip().startswith(GENERATED),
        preamble_line=_line_of(whole, after.strip()) if after.strip() else 0,
        first_section=first_section,
    )
    for n, (name, number, body) in enumerate(chunks):
        end = chunks[n + 1][1] - 1 if n + 1 < len(chunks) else len(lines)
        blank = next((i for i, row in enumerate(body) if row.strip()), len(body))
        section = Section(name, "\n".join(body).strip(), number, number + 1 + blank, end)
        key = normal(name)
        if key in _KNOWN and key not in report.sections:
            report.sections[key] = section
        else:
            report.extra.append(section)
    return report


def _line_of(text: str, part: str) -> int:
    """The line (from 1) of the first character of ``part`` in ``text``."""
    at = text.find(part)
    return text.count("\n", 0, at) + 1 if at >= 0 else 0


def list_items(body: str) -> tuple[list[Item], str]:
    """The top-level list items of ``body``, and the text that is not in one.

    An item goes on over a line that is indented, or over a plain line just
    under it. A blank line ends the item unless the next line is indented.
    """
    lines = body.split("\n")
    outside = _lines_outside_fences(lines)
    items: list[list[str]] = []
    starts: list[int] = []
    rest: list[str] = []
    current: list[str] | None = None
    for index, (line, free) in enumerate(zip(lines, outside, strict=True)):
        match = _ITEM.match(line) if free else None
        if match:
            current = [match.group(2)]
            items.append(current)
            starts.append(index)
            continue
        if current is not None:
            indented = line.startswith(("  ", "\t"))
            if not line.strip():
                following = next((n for n in lines[index + 1 :] if n.strip()), "")
                if following.startswith(("  ", "\t")):
                    current.append("")
                    continue
                current = None
            elif indented or (current[-1].strip() and free and not _FENCE.match(line)):
                current.append(line.strip() if not indented else _dedent(line))
                continue
            else:
                current = None
        rest.append(line)
    found = [_item(lines, start) for lines, start in zip(items, starts, strict=True)]
    return found, "\n".join(rest).strip()


def _dedent(line: str) -> str:
    if line.startswith("\t"):
        return line[1:]
    return line[min(len(line) - len(line.lstrip(" ")), 4) :]


def _item(lines: list[str], start: int) -> Item:
    text = "\n".join(lines).strip()
    match = _LEAD.match(text)
    if match is None:
        return Item(text=text, line=start)
    lead = (match.group(1) or match.group(2) or "").strip()
    return Item(text=text, lead=lead, body=match.group(3).strip(), line=start)


def decision_question(item: Item) -> tuple[str, str]:
    """The question of a decision and its context, as Markdown.

    The question is the bold lead. With no lead, it is the first line."""
    if item.lead:
        return item.lead, item.body
    first, _, rest = item.text.partition("\n")
    return first.strip(), rest.strip()


def plain(markdown: str) -> str:
    """Inline Markdown as plain text, for the copy text of a decision."""
    text = _LINK.sub(lambda m: m.group("title"), markdown)
    text = re.sub(r"(\*\*|__)(.+?)\1", r"\2", text)
    text = re.sub(r"`([^`]*)`", r"\1", text)
    return " ".join(text.split())


def output_lines(body: str) -> list[OutputLine]:
    """The lines of the Outputs section: ``kind: [title](ref) — note``,
    ``kind: `ref` — note``, or ``kind: ref — title``. A line that has none of
    these parts gives a line with only a note."""
    lines: list[OutputLine] = []
    for item in list_items(body)[0]:
        text = " ".join(item.text.split())
        if is_none(text):
            continue
        kind = ""
        match = _KIND.match(text)
        if match:
            kind, text = match.group("kind").strip(), match.group("rest")
        link = _LINK.search(text)
        found = link or _CODE.search(text)
        if found is not None:
            ref = found.group("ref").strip().strip("<>")
            before = _TRAIL_DASH.sub("", text[: found.start()]).strip()
            title = link.group("title").strip() if link else before
            note = _LEAD_DASH.sub("", text[found.end() :]).strip()
            lines.append(OutputLine(kind, ref, title, note, item.line))
            continue
        head, _, tail = (part.strip() for part in _split_dash(text))
        if not kind:
            lines.append(OutputLine("", "", "", text.strip(), item.line))
        elif " " not in head:
            lines.append(OutputLine(kind, head, tail, "", item.line))
        else:
            lines.append(OutputLine(kind, "", head, tail, item.line))
    return lines


def _split_dash(text: str) -> tuple[str, str, str]:
    parts = _DASH.split(text, maxsplit=1)
    return (parts[0], " — ", parts[1]) if len(parts) > 1 else (parts[0], "", "")


def turns(cost: str | None) -> int | None:
    """The number of turns in the Cost section, or None when it has none."""
    for pattern in _TURNS:
        match = pattern.search(cost or "")
        if match:
            digits = re.sub(r"\D", "", match.group(1))
            if digits:
                return int(digits)
    return None


def plan_progress(plan: str | None) -> PlanProgress:
    """The task boxes of ``plan``: ticked over all, and the next step.

    The next step is the first open box that holds ``**Next:**`` (with the
    marker taken out), else the first open box, else ""."""
    lines = (plan or "").split("\n")
    done = total = 0
    marked = first = ""
    for line, free in zip(lines, _lines_outside_fences(lines), strict=True):
        match = _BOX.match(line) if free else None
        if not match:
            continue
        total += 1
        if match.group(1) in "xX":
            done += 1
            continue
        text = match.group(2).strip()
        if not first:
            first = text
        if not marked and _NEXT.search(text):
            marked = _NEXT.sub("", text, count=1).strip()
    return PlanProgress(done=done, total=total, next_step=marked or first)
