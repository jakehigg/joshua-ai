"""The report: the cost section, the report the runner generates, and the state."""

from __future__ import annotations

import pytest
from fakes import FIXED_NOW, FakeStore
from joshua_assignments import report
from joshua_assignments.store import STATES, STATUSES, state, statuses_of

WORKER = """# Audit the gitops repo
## What was asked
Audit it.
## What was done
Read it.
## Outputs
- issue: ops#1 — First
## Decisions for you
- Close issue 4?
## Follow-ups
None."""


def costly(**fields) -> dict:
    return {
        "id": 1,
        "spec": {"goal": "Audit the gitops repo. Then file issues.", "model": "sonnet"},
        "model": "claude-sonnet-5",
        "input": 400,
        "output": 80,
        "cache_read": 4000,
        "cache_write": 20,
        "turns": 22,
        "working_s": 3900,
        **fields,
    }


@pytest.mark.parametrize(
    ("status", "expected"),
    [
        ("queued", "queued"),
        ("running", "in_progress"),
        ("waiting", "in_progress"),
        ("paused_limits", "in_progress"),
        ("done", "completed"),
        ("failed", "completed"),
        ("cancelled", "completed"),
        ("budget_exceeded", "completed"),
        ("time_exceeded", "completed"),
    ],
)
def test_the_state_of_each_status(status: str, expected: str) -> None:
    assert state(status) == expected


def test_the_statuses_of_each_state_cover_every_status_once() -> None:
    assert STATES == ("queued", "in_progress", "completed")
    assert statuses_of("in_progress") == ("running", "waiting", "paused_limits")
    assert sorted(s for name in STATES for s in statuses_of(name)) == sorted(STATUSES)


def test_the_cost_section() -> None:
    assert report.cost_section(costly()) == (
        "## Cost\n\n"
        "- Tokens: 4500 in all (input 400, output 80, cache read 4000, cache write 20)\n"
        "- Turns: 22\n"
        "- Working time: 1h 05m\n"
        "- Model: sonnet (claude-sonnet-5)"
    )
    assert "- Model: unknown" in report.cost_section({})


def test_with_cost_replaces_an_earlier_cost_section() -> None:
    once = report.with_cost(WORKER, costly())
    assert once.startswith(WORKER) and once.count("## Cost") == 1
    twice = report.with_cost(once, costly(turns=30))
    assert twice.count("## Cost") == 1 and "- Turns: 30" in twice
    assert report.without_cost(twice) == WORKER


def test_the_section_reader() -> None:
    assert report.section(WORKER, report.DECISIONS_HEADING) == "- Close issue 4?"
    assert report.section(WORKER, "## Missing") is None
    assert report.section(None, report.DECISIONS_HEADING) is None


def test_a_generated_report_has_the_headings_of_a_worker_report() -> None:
    row = costly(
        status="failed",
        error="http_500",
        plan="# Plan\n1. [x] Clone.\n2. [x] Read.\n3. [ ] **Next:** File.\n- [ ] Tidy.",
        outputs=[
            {"kind": "issue", "ref": "https://gitlab.example.net/infra/backlog/-/issues/1",
             "title": "First"},
            {"kind": "task", "ref": "ops#`2`", "title": "Second"},
            {"kind": "k", "ref": "r"},
            "not an output",
        ],
    )  # fmt: skip
    checkpoint = {"at": FIXED_NOW, "note": "cloned.\nNext: read"}
    text = report.generated(row, checkpoint, FIXED_NOW, "UTC")
    lines = text.splitlines()
    assert lines[0] == "# Audit the gitops repo"
    assert lines[2].startswith("Generated by the runner at failed, 2026-03-04 05:06 UTC. ")
    headings = [line for line in lines if line.startswith("## ")]
    assert headings == [
        "## Highlights",
        "## What was asked",
        "## What was done",
        "## Outputs",
        "## Decisions for you",
        "## Follow-ups",
    ]
    assert report.section(text, "## Highlights") == (
        "- **Stopped at failed** The stop reason is `http_500`.\n"
        "- **2 of 4 steps** are ticked in the plan."
    )
    assert report.section(text, "## What was asked") == "Audit the gitops repo. Then file issues."
    done = report.section(text, "## What was done")
    assert done.startswith("The plan below shows the progress.\n\n")
    assert "The last checkpoint (2026-03-04 05:06 UTC): cloned. Next: read" in done
    assert "3. [ ] **Next:** File." in done
    assert report.section(text, "## Outputs") == (
        "- issue: [First](https://gitlab.example.net/infra/backlog/-/issues/1)\n"
        "- task: Second — `ops#'2'`\n"
        "- k: `r`"
    )
    assert report.section(text, "## Decisions for you") == "None."
    assert report.section(text, "## Follow-ups") == "None."
    assert report.is_generated(text) and not report.is_generated(WORKER)


def test_a_generated_report_with_a_question_and_nothing_recorded() -> None:
    row = {"id": 2, "status": "waiting", "open_question": "Which\nproject?", "spec": {"goal": "g"}}
    text = report.generated(row, None, FIXED_NOW, "UTC")
    assert report.section(text, "## Highlights") == (
        "- **Stopped at waiting** It has a question for you, under Decisions for you."
    )
    assert report.section(text, "## Decisions for you") == (
        "1. **Which project?** The assignment waits for your answer."
    )
    assert "No plan was written." in text and "None recorded." in text
    assert "The last checkpoint" not in text


def test_the_stop_reason_of_each_kind_of_stop() -> None:
    record = {"window": "five_hour", "used_pct": 81, "ceiling": 80, "resets_at": None}
    limits = {"status": "paused_limits", "stopped_at_limits": record}
    assert "the 5-hour window is at 81 percent" in report.stop_reason(limits, "UTC")
    cancelled = {"status": "cancelled"}
    assert report.stop_reason(cancelled, "UTC") == "It was stopped with cancel_assignment."
    assert report.stop_reason({"status": "done"}, "UTC") == "The worker wrote no report."


def test_plan_steps_counts_the_check_boxes() -> None:
    assert report.plan_steps("1. [x] a\n2) [X] b\n- [ ] c\n* [ ] d\ntext [x] e") == (2, 4)
    assert report.plan_steps("No boxes.") == (0, 0)
    assert report.plan_steps(None) == (0, 0)
    text = report.generated({"status": "failed", "plan": "No boxes."}, None, FIXED_NOW, "UTC")
    assert "steps**" not in text


async def test_finalize_generates_once_and_keeps_a_worker_report() -> None:
    store = FakeStore()
    row = await store.create(person_id="alex", conversation_id=None, spec={"goal": "g"}, model="m")
    await store.update(row["id"], status="waiting", open_question="Q?")
    await report.finalize(store, row["id"], FIXED_NOW, "UTC")
    first = store.rows[row["id"]]["report"]
    assert report.is_generated(first) and first.count("## Cost") == 1
    # A later stop writes the generated report again, with the new state.
    await store.update(row["id"], status="time_exceeded", open_question=None, error="working_time")
    await report.finalize(store, row["id"], FIXED_NOW, "UTC")
    second = store.rows[row["id"]]["report"]
    assert "Generated by the runner at time_exceeded" in second and "Q?" not in second
    # A report of the worker replaces it, and a stop only adds the cost.
    await store.write_report(row["id"], WORKER)
    await report.finalize(store, row["id"], FIXED_NOW, "UTC")
    assert store.rows[row["id"]]["report"].startswith(WORKER + "\n\n## Cost")
    await report.finalize(store, 99, FIXED_NOW, "UTC")


async def test_finalize_never_raises(caplog) -> None:
    store = FakeStore()

    async def broken(assignment_id: int) -> None:
        raise RuntimeError("db.example went away")

    store.get = broken  # type: ignore[method-assign]
    with caplog.at_level("WARNING", logger="joshua_assignments.report"):
        await report.finalize(store, 1, FIXED_NOW, "UTC")
    assert "the report was not written" in caplog.text and "db.example" not in caplog.text


def test_a_heading_of_the_plan_cannot_take_the_place_of_a_section() -> None:
    plan = "# Plan\n## Outputs\n- [ ] one\n## Decisions\n```\n## kept in code\n```\n###### deep"
    text = report.generated({"status": "failed", "plan": plan}, None, FIXED_NOW, "UTC")
    # A line in a fenced code block is not a heading, so it stays as it is.
    headings = [
        line for line in text.splitlines() if line.startswith("## ") and line != "## kept in code"
    ]
    assert headings == [
        "## Highlights",
        "## What was asked",
        "## What was done",
        "## Outputs",
        "## Decisions for you",
        "## Follow-ups",
    ]
    done = text.split("## What was done\n\n", 1)[1].split("\n\n## Outputs", 1)[0]
    assert "### Plan\n#### Outputs\n- [ ] one\n#### Decisions" in done
    assert "```\n## kept in code\n```" in done
    assert done.endswith("###### deep")
