"""The report of an assignment: the artifact that a person and Joshua read.

The worker writes the report with ``write_report``, in the shape that the
system prompt gives (``SECTIONS``). When the assignment stops, the runner
appends the ``## Cost`` section. When it stops in any status but ``done`` and
the worker wrote no report, the runner writes one: ``generated``. A
generated report says so on its second line, so a later stop writes it
again, and a report of the worker replaces it.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any

from joshua_shared.log import get_logger

from joshua_assignments.budget import duration_text, limits_stop_text
from joshua_assignments.spec import assignment_title
from joshua_assignments.store import USAGE_FIELDS, Store

logger = get_logger("joshua_assignments.report")

SECTIONS = (
    "What was asked",
    "What was done",
    "Outputs",
    "Decisions for you",
    "Follow-ups",
)
COST_HEADING = "## Cost"
DECISIONS_HEADING = "## Decisions for you"
GENERATED = "Generated by the runner at"
MAX_PLAN = 64 * 1024
MAX_REPORT = 256 * 1024


def _lines(text: str | None) -> list[str]:
    return (text or "").strip().splitlines()


def is_generated(report: str | None) -> bool:
    """True when the runner wrote ``report``, not the worker."""
    lines = [line for line in _lines(report) if line.strip()]
    return len(lines) > 1 and lines[1].startswith(GENERATED)


def has_worker_report(row: dict[str, Any]) -> bool:
    """True when the worker wrote the report of ``row``."""
    report = row.get("report")
    return bool((report or "").strip()) and not is_generated(report)


def without_cost(report: str) -> str:
    """``report`` with no ``## Cost`` section: the runner writes that section."""
    lines = report.rstrip().splitlines()
    for i in range(len(lines) - 1, -1, -1):
        if lines[i].strip() == COST_HEADING:
            return "\n".join(lines[:i]).rstrip()
    return report.rstrip()


def section(report: str | None, heading: str) -> str | None:
    """The text under ``heading`` (such as ``## Decisions for you``), up to the next heading."""
    out: list[str] = []
    inside = False
    for line in _lines(report):
        if line.strip() == heading:
            inside = True
            continue
        if inside and line.startswith("## "):
            break
        if inside:
            out.append(line)
    text = "\n".join(out).strip()
    return text or None


def output_line(output: dict[str, Any]) -> str:
    """One output as ``kind: ref — title``."""
    kind, ref = output.get("kind") or "", output.get("ref") or ""
    title = output.get("title") or ""
    return f"{kind}: {ref} — {title}" if title else f"{kind}: {ref}"


def cost_section(row: dict[str, Any]) -> str:
    """The ``## Cost`` section, from the counts of the row."""
    counts = {name: int(row.get(name) or 0) for name in USAGE_FIELDS}
    spec = row.get("spec") or {}
    model = str(spec.get("model") or "")
    model_id = str(row.get("model") or "")
    named = f"{model} ({model_id})" if model and model_id and model != model_id else model_id
    return "\n".join(
        [
            COST_HEADING,
            "",
            f"- Tokens: {sum(counts.values())} in all (input {counts['input']}, output "
            f"{counts['output']}, cache read {counts['cache_read']}, cache write "
            f"{counts['cache_write']})",
            f"- Turns: {int(row.get('turns') or 0)}",
            f"- Working time: {duration_text(int(row.get('working_s') or 0))}",
            f"- Model: {named or 'unknown'}",
        ]
    )


def with_cost(report: str, row: dict[str, Any]) -> str:
    """``report`` with a new ``## Cost`` section at the end."""
    return f"{without_cost(report)}\n\n{cost_section(row)}\n"


def _time_text(at: datetime) -> str:
    return at.astimezone(UTC).strftime("%Y-%m-%d %H:%M UTC")


def state_text(row: dict[str, Any], timezone: str) -> str:
    """The State section of a generated report: the status and why it stopped."""
    status = str(row.get("status") or "unknown")
    lines = [f"Status: {status}."]
    if status == "paused_limits" and row.get("stopped_at_limits"):
        lines.append(limits_stop_text(row["stopped_at_limits"], timezone))
    elif row.get("open_question"):
        lines += ["The open question:", "", str(row["open_question"]).strip()]
    elif status == "cancelled":
        lines.append("It was stopped with cancel_assignment.")
    elif row.get("error"):
        lines.append(f"The stop reason: {row['error']}.")
    return "\n".join(lines)


def generated(
    row: dict[str, Any], checkpoint: dict[str, Any] | None, at: datetime, timezone: str
) -> str:
    """The report that the runner writes when the worker wrote none. With no cost."""
    spec = row.get("spec") or {}
    outputs = row.get("outputs") or []
    note = (checkpoint or {}).get("note")
    when = (checkpoint or {}).get("at")
    if note and isinstance(when, datetime):
        last = f"{_time_text(when)}: {note}"
    else:
        last = note or "None."
    parts = [
        f"# {assignment_title(spec)}",
        f"{GENERATED} {row.get('status')}, {_time_text(at)}.",
        "## What was asked",
        str(spec.get("goal") or "").strip() or "No goal.",
        "## State",
        state_text(row, timezone),
        "## Plan",
        (row.get("plan") or "").strip() or "No plan was written.",
        "## Outputs",
        "\n".join(f"- {output_line(o)}" for o in outputs) if outputs else "None recorded.",
        "## Last checkpoint",
        last,
    ]
    return "\n\n".join(parts)


async def finalize(store: Store, assignment_id: int, at: datetime, timezone: str) -> None:
    """Write the report of a stopped assignment: the worker's, or a generated one, with cost.

    A failure is logged by its type and does not stop the caller.
    """
    try:
        row = await store.get(assignment_id)
        if row is None:
            return
        if has_worker_report(row):
            body = str(row["report"])
        else:
            checkpoint = await store.last_checkpoint(assignment_id)
            body = generated(row, checkpoint, at, timezone)
        await store.write_report(assignment_id, with_cost(body, row))
    except Exception as exc:  # noqa: BLE001 — a missing report never blocks the event
        logger.warning(
            {
                "message": "the report was not written",
                "assignment_id": assignment_id,
                "error": type(exc).__name__,
            }
        )
